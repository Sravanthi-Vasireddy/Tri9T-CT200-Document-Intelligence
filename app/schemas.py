from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class NodeType(str, Enum):
    DOCUMENT = "document"
    SECTION = "section"
    PARAGRAPH = "paragraph"
    TABLE = "table"
    LIST = "list"
    LIST_ITEM = "list_item"
    FIGURE = "figure"


class TableData(BaseModel):
    headers: List[str] = Field(default_factory=list)
    rows: List[List[Optional[str]]] = Field(default_factory=list)
    row_count: int = 0
    col_count: int = 0
    bbox: Optional[List[float]] = None


class DocumentNode(BaseModel):
    """
    Represents a discrete element within the reconstructed hierarchical document tree.
    """
    id: str = Field(..., description="Unique version-specific node ID (e.g. 'v1_sec_2_1')")
    logical_key: str = Field(..., description="Version-independent logical key for cross-version matching (e.g. 'sec_2.1')")
    node_type: NodeType = Field(..., description="Type of node: document, section, paragraph, table, list, figure")
    title_or_text: str = Field(..., description="Heading title or body text content")
    section_number: Optional[str] = Field(None, description="Section numbering if available (e.g. '1', '2.1', '2.1.1.1', '3.4')")
    hierarchy_level: int = Field(..., description="Nesting level in tree (0=doc, 1=H1, 2=H2, 3/4=H3/H4, >4=content)")
    parent_id: Optional[str] = Field(None, description="Parent node ID, or None if root")
    children_ids: List[str] = Field(default_factory=list, description="Ordered references to child node IDs")
    page_start: int = Field(..., description="Starting 1-based page number")
    page_end: int = Field(..., description="Ending 1-based page number")
    reading_order_index: int = Field(..., description="Physical sequence order in source PDF")
    content_hash: str = Field(..., description="SHA-256 hash of normalized content/payload")
    extraction_confidence: float = Field(default=1.0, description="Extraction confidence score between 0.0 and 1.0")
    is_uncertain: bool = Field(default=False, description="Flag indicating extraction uncertainty or anomaly")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Supplementary metadata (e.g. table_data, list_items, font info)")


class DocumentTree(BaseModel):
    """
    Complete hierarchical document tree representation with metadata.
    """
    document_id: str = Field(..., description="Identifier for document, e.g. 'ct200_manual'")
    version: str = Field(..., description="Version string, e.g. 'v1' or 'v2'")
    source_file: str = Field(..., description="Path to source PDF")
    title: str = Field(..., description="Document title")
    total_pages: int = Field(..., description="Total pages in source document")
    root_node_id: str = Field(..., description="ID of root document node")
    nodes: Dict[str, DocumentNode] = Field(default_factory=dict, description="Mapping from node ID to DocumentNode")
    reading_order: List[str] = Field(default_factory=list, description="Ordered list of node IDs by physical reading flow")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Document-level metadata (e.g. ocr_used, timestamps)")


class ValidationResult(BaseModel):
    """
    Report generated by tree validation checks.
    """
    is_valid: bool = Field(..., description="True if no fatal errors detected")
    errors: List[str] = Field(default_factory=list, description="Fatal consistency or structural errors")
    warnings: List[str] = Field(default_factory=list, description="Non-fatal warnings or flags")
    stats: Dict[str, Any] = Field(default_factory=dict, description="Structural statistics (node counts, table counts, etc.)")


class NodeChangeStatus(str, Enum):
    UNCHANGED = "unchanged"
    CHANGED = "changed"
    ADDED = "added"
    REMOVED = "removed"
    AMBIGUOUS = "ambiguous"


class NodeMatch(BaseModel):
    logical_key: str
    status: NodeChangeStatus
    prev_node_id: Optional[str] = None
    curr_node_id: Optional[str] = None
    prev_hash: Optional[str] = None
    curr_hash: Optional[str] = None
    node_type: str
    title_or_text: str
    details: Optional[str] = None


class IngestionSummary(BaseModel):
    version_id: str
    version_number: str
    document_id: str
    source_filename: str
    file_hash: str
    total_pages: int
    total_nodes: int
    added_nodes: int = 0
    removed_nodes: int = 0
    changed_nodes: int = 0
    unchanged_nodes: int = 0
    ambiguous_matches: int = 0
    already_ingested: bool = False
    diff_details: List[NodeMatch] = Field(default_factory=list)

